/** Ícono de canal en su color de marca, dentro de un disco chico. */
export function ChannelDot({
  channel,
  className,
}: {
  channel: Channel
  className?: string
}) {
  return (
    <span
      className={cn(
        "inline-grid size-4 place-items-center rounded-full ring-2 ring-obsidian",
        channel === "whatsapp" ? "bg-whatsapp text-obsidian" : "bg-instagram text-white",
        className
      )}
      aria-label={channel === "whatsapp" ? "WhatsApp" : "Instagram"}
    >
      {channel === "whatsapp" ? (
        <WhatsAppIcon className="size-2.5" />
      ) : (
        <InstagramIcon className="size-2.5" />
      )}
    </span>
  )
}

